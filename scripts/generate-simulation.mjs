import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';

// Illustrative scenario only. This script never reads the observed Discord files.
const workspace = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputDir = path.join(workspace, 'dist', 'data');
const seed = 20261108;
const allChallengeIds = ['revs-casino', 'dashboard-royale', 'build-a-dataset', 'house-edge', 'heads-up', 'hitachi', 'heb', 'databricks'];
const flags = { source_type: 'synthetic', is_observed: false, scenario_only: true };

function mulberry32(initialSeed) {
  let state = initialSeed >>> 0;
  return () => {
    state += 0x6D2B79F5;
    let value = state;
    value = Math.imul(value ^ value >>> 15, value | 1);
    value ^= value + Math.imul(value ^ value >>> 7, value | 61);
    return ((value ^ value >>> 14) >>> 0) / 4294967296;
  };
}
const random = mulberry32(seed);
const integer = (min, max) => min + Math.floor(random() * (max - min + 1));

// Deliberately varied assumptions for exercising the interface, not estimated
// frequencies. The allocation is disjoint within each fictional four-person team.
const choices = [
  [['revs-casino', 'active', 2], ['house-edge', 'active', 2]],
  [['dashboard-royale', 'active', 3], ['databricks', 'active', 1]],
  [['heads-up', 'active', 4], ['revs-casino', 'stopped', 0]],
  [['hitachi', 'active', 3], ['databricks', 'considering', 0]],
  [['build-a-dataset', 'active', 3], ['revs-casino', 'considering', 0]],
  [['heb', 'active', 4], ['dashboard-royale', 'stopped', 0], ['revs-casino', 'considering', 0]],
  [['revs-casino', 'submitting', 2], ['heads-up', 'active', 2]],
  [['house-edge', 'active', 3], ['dashboard-royale', 'considering', 0], ['databricks', 'active', 1]],
  [['heb', 'active', 2], ['build-a-dataset', 'active', 1], ['databricks', 'active', 1]],
];
const isCurrent = status => ['active', 'submitting'].includes(status);
const records = choices.flatMap((teamChoices, index) => {
  const teamId = `SIM-T${String(index + 1).padStart(2, '0')}`;
  return teamChoices.map(([challengeId, status, allocation]) => ({
    record_id: `${teamId}--${challengeId}`,
    ...flags,
    team_id: teamId,
    challenge_id: challengeId,
    status,
    person_count_allocated: allocation,
    effort_hours: status === 'considering' ? 0 : status === 'stopped' ? integer(1, 6) / 2 : status === 'submitting' ? integer(6, 15) / 2 : integer(2, 14) / 2,
    simulated_difficulty_1_5: status === 'considering' ? null : status === 'stopped' ? integer(3, 5) : status === 'submitting' ? integer(1, 3) : integer(2, 5),
    simulated_prize_importance_1_5: integer(1, 5),
    assumption_note: 'Fictional assignment and ratings; no participant was approached or surveyed to produce this row.',
  }));
});
const teams = choices.map((teamChoices, index) => {
  const teamId = `SIM-T${String(index + 1).padStart(2, '0')}`;
  const allocation = teamChoices.reduce((total, row) => total + row[2], 0);
  return {
    team_id: teamId,
    ...flags,
    profile_label: `Fictional team ${String(index + 1).padStart(2, '0')}`,
    team_size: 4,
    selected_challenge_count: teamChoices.length,
    active_or_submitting_challenge_count: teamChoices.filter(row => isCurrent(row[1])).length,
    members_allocated: allocation,
    members_unallocated: 4 - allocation,
    assumption_note: 'Four fictional members per team, as requested for the scenario; no real team identity or membership is represented.',
  };
});

const challengeSummaries = allChallengeIds.map(challengeId => {
  const selected = records.filter(row => row.challenge_id === challengeId);
  return {
    challenge_id: challengeId,
    ...flags,
    selected_fictional_teams: selected.length,
    active_or_submitting_fictional_teams: selected.filter(row => isCurrent(row.status)).length,
    considering_fictional_teams: selected.filter(row => row.status === 'considering').length,
    stopped_fictional_teams: selected.filter(row => row.status === 'stopped').length,
    fictional_members_allocated: selected.reduce((total, row) => total + row.person_count_allocated, 0),
  };
});

const metadata = {
  title: 'Illustrative nine-team scenario — synthetic data',
  ...flags,
  seed,
  algorithm: 'Fixed illustrative choice/status/allocation matrix; Mulberry32(seed) for assumed effort and ratings in file order.',
  generator: 'scripts/generate-simulation.mjs',
  provenance: 'Generated by the assistant for a fictional scenario requested by the user. No interviews, approaches, survey responses or participant observations produced these values.',
  relationship_to_observed_data: 'Independent of the ten verified Discord message records. No observed counts or message categories are inputs to this generator.',
  generated_value_ranges: {
    effort_hours: { active: '1–7 in half-hour increments', submitting: '3–7.5 in half-hour increments', stopped: '0.5–3 in half-hour increments', considering: 0 },
    simulated_difficulty_1_5: { active: [2, 5], submitting: [1, 3], stopped: [3, 5], considering: null },
    simulated_prize_importance_1_5: [1, 5],
    note: 'These ranges are author-designed assumptions, not measured distributions.',
  },
  assumptions: [
    'Exactly nine fictional teams with four fictional members each; 36 fictional members in total.',
    'Each team has two or three selected challenge rows. All eight official challenge IDs appear in the scenario.',
    'Challenge choices and statuses are deliberately varied for interface demonstration, not estimated from event participation or prize values.',
    'Members are allocated to one active or submitting challenge each at this scenario snapshot. Allocations within a team never exceed four; considering and stopped rows have zero currently allocated members.',
    'Two fictional members are unallocated. The 34 allocated members plus two unallocated members equal 36.',
    'Effort is assumed elapsed working hours on that challenge, not person-hours. A considering row has zero assumed effort; these are not event timestamps.',
    'Difficulty is an invented integer from 1 (easy) to 5 (difficult), or null for considering. Prize importance is an invented integer from 1 (none) to 5 (high). Neither is self-reported.',
    'No winner, final placement, probability of winning, total event participation or causal relationship is modeled.',
  ],
  counts: {
    fictional_team_count: teams.length,
    assumed_members_per_team: 4,
    fictional_member_count: teams.reduce((total, row) => total + row.team_size, 0),
    team_challenge_row_count: records.length,
    allocated_fictional_members: teams.reduce((total, row) => total + row.members_allocated, 0),
    unallocated_fictional_members: teams.reduce((total, row) => total + row.members_unallocated, 0),
    challenge_count: allChallengeIds.length,
  },
  eligibility_note: 'Synthetic scenario data is not newly collected primary field data and does not establish compliance with Build-A-Dataset collection requirements.',
};

// Validate factual consistency of this fictional scenario before writing it.
assert.equal(teams.length, 9);
assert.equal(metadata.counts.fictional_member_count, 36);
assert.equal(new Set(records.map(row => row.record_id)).size, records.length);
assert.deepEqual([...new Set(records.map(row => row.challenge_id))].sort(), [...allChallengeIds].sort());
for (const team of teams) {
  const rows = records.filter(row => row.team_id === team.team_id);
  assert.ok(rows.length >= 1 && rows.length <= 3);
  assert.equal(team.team_size, 4);
  assert.equal(rows.reduce((total, row) => total + row.person_count_allocated, 0), team.members_allocated);
  assert.ok(team.members_allocated <= team.team_size);
  assert.equal(team.members_allocated + team.members_unallocated, 4);
}
for (const row of [...teams, ...records, ...challengeSummaries]) {
  assert.equal(row.source_type, 'synthetic');
  assert.equal(row.is_observed, false);
  assert.equal(row.scenario_only, true);
}
for (const row of records) {
  assert.ok(Number.isInteger(row.person_count_allocated) && row.person_count_allocated >= 0);
  assert.ok(['considering', 'active', 'submitting', 'stopped'].includes(row.status));
  if (!isCurrent(row.status)) assert.equal(row.person_count_allocated, 0);
  assert.ok(row.simulated_difficulty_1_5 === null || Number.isInteger(row.simulated_difficulty_1_5) && row.simulated_difficulty_1_5 >= 1 && row.simulated_difficulty_1_5 <= 5);
  assert.ok(Number.isInteger(row.simulated_prize_importance_1_5) && row.simulated_prize_importance_1_5 >= 1 && row.simulated_prize_importance_1_5 <= 5);
}
assert.equal(metadata.counts.allocated_fictional_members + metadata.counts.unallocated_fictional_members, 36);
assert.equal(challengeSummaries.reduce((total, row) => total + row.fictional_members_allocated, 0), metadata.counts.allocated_fictional_members);

fs.mkdirSync(outputDir, { recursive: true });
fs.writeFileSync(path.join(outputDir, 'simulated-teams.json'), `${JSON.stringify({ schema_version: 1, metadata, records: teams }, null, 2)}\n`);
fs.writeFileSync(path.join(outputDir, 'simulated-team-challenges.json'), `${JSON.stringify({ schema_version: 1, metadata, challenge_summaries: challengeSummaries, records }, null, 2)}\n`);
console.log(JSON.stringify(metadata.counts));
